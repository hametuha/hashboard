/**
 * Integration tests across components (issue #46).
 *
 * Unit tests mock sibling components, so they cannot catch naming,
 * props contract, or dependency drift between components (see #44).
 * These tests use the real built components and the real wp-dependencies.json.
 *
 * @jest-environment jsdom
 */
import React from 'react';
import { render, fireEvent, screen } from '@testing-library/react';
import '@testing-library/jest-dom';

const fs = require( 'fs' );
const path = require( 'path' );

const root = path.resolve( __dirname, '..' );
const componentsDir = path.join( root, 'src/js/components' );
const dependencies = require( '../wp-dependencies.json' );

/**
 * Handle name generated by grab-deps for a component file.
 *
 * @param {string} file File name such as date-range.js.
 * @return {string} Handle such as hb-components-date-range.
 */
const handleOf = ( file ) => 'hb-components-' + file.replace( /\.jsx?$/, '' );

const sources = fs.readdirSync( componentsDir )
	.filter( ( file ) => /\.jsx?$/.test( file ) )
	.map( ( file ) => ( {
		file,
		handle: handleOf( file ),
		code: fs.readFileSync( path.join( componentsDir, file ), 'utf8' ),
	} ) );

// Exported name => handle of the file exporting it.
const exportedBy = {};
sources.forEach( ( { code, handle } ) => {
	for ( const [ , name ] of code.matchAll( /^export const (\w+)/gm ) ) {
		exportedBy[ name ] = handle;
	}
} );

/**
 * Component names a file reads from the runtime global registry.
 *
 * Covers `hb.components.X`, `window.hb?.components?.X`,
 * and `const { X, Y } = hb.components;`.
 *
 * @param {string} code Source code.
 * @return {string[]} Referenced names.
 */
const referencedComponents = ( code ) => {
	// Ignore comments.
	const body = code.replace( /\/\*[\s\S]*?\*\//g, '' ).replace( /\/\/.*$/gm, '' );
	const names = new Set();
	for ( const [ , name ] of body.matchAll( /hb\??\.components\??\.(\w+)/g ) ) {
		names.add( name );
	}
	for ( const [ , list ] of body.matchAll( /const\s*\{([^}]+)\}\s*=\s*(?:window\.)?hb\??\.components/g ) ) {
		list.split( ',' ).map( ( s ) => s.split( ':' )[ 0 ].trim() ).filter( Boolean ).forEach( ( n ) => names.add( n ) );
	}
	return [ ...names ];
};

const references = sources.flatMap( ( { file, handle, code } ) =>
	referencedComponents( code ).map( ( name ) => [ file, handle, name ] )
);

describe( 'Runtime global references', () => {
	test( 'at least the known cross-component references are detected', () => {
		const pairs = references.map( ( [ file, , name ] ) => `${ file }:${ name }` );
		expect( pairs ).toEqual( expect.arrayContaining( [
			'period-picker.js:DateRange',
			'list-table.js:Pagination',
			'list-table.js:LoadingIndicator',
			'post-list.js:ListTable',
		] ) );
	} );

	test.each( references )( '%s (%s) uses %s, which some component exports', ( file, handle, name ) => {
		expect( exportedBy[ name ] ).toBeDefined();
	} );

	test.each( references )( '%s (%s) declares the dependency providing %s', ( file, handle, name ) => {
		const provider = exportedBy[ name ];
		if ( ! provider || provider === handle ) {
			return;
		}
		const entry = dependencies.find( ( dep ) => dep.handle === handle );
		expect( entry ).toBeDefined();
		expect( entry.deps ).toContain( provider );
	} );
} );

describe( 'PeriodPicker with real DateRange', () => {
	beforeAll( () => {
		// Load in dependency order as the browser does.
		require( '../assets/js/components/date-range.js' );
		require( '../assets/js/components/period-picker.js' );
	} );

	const renderCustom = ( props = {} ) => {
		const { PeriodPicker } = window.hb.components;
		const utils = render( React.createElement( PeriodPicker, props ) );
		fireEvent.click( utils.container.querySelector( 'input[value="custom"]' ) );
		return utils;
	};

	test( 'Custom renders the real DateRange instead of the fallback', () => {
		const { container } = renderCustom();
		expect( screen.queryByText( 'DateRange component not available' ) ).not.toBeInTheDocument();
		expect( container.querySelector( '.hb-period-dates .hb-date-range-trigger' ) ).toBeInTheDocument();
	} );

	test( 'DateRange opens two native DatePickers', () => {
		const { container } = renderCustom();
		fireEvent.click( container.querySelector( '.hb-date-range-trigger' ) );
		expect( document.querySelectorAll( '.components-datetime__date' ) ).toHaveLength( 2 );
	} );

	test( 'DateRange callback reaches PeriodPicker onDateChanged', () => {
		const onDateChanged = jest.fn();
		renderCustom( { onDateChanged } );
		expect( onDateChanged ).toHaveBeenCalledWith( expect.any( Date ), expect.any( Date ) );
	} );
} );
